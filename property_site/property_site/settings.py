# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

# Production uses Postgres via DATABASE_URL (Vercel sets it when you add a database).
# Locally, with no DATABASE_URL, it falls back to SQLite.
_db_url = os.environ.get('DATABASE_URL')
if _db_url:
    _u = urllib.parse.urlparse(_db_url)
    _opts = {k: v for k, v in urllib.parse.parse_qsl(_u.query) if k in ('sslmode', 'channel_binding')}
    _opts.setdefault('sslmode', 'require' if ON_VERCEL else 'prefer')
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': _u.path.lstrip('/'),
            'USER': urllib.parse.unquote(_u.username or ''),
            'PASSWORD': urllib.parse.unquote(_u.password or ''),
            'HOST': _u.hostname,
            'PORT': _u.port or 5432,
            'OPTIONS': _opts,
            'DISABLE_SERVER_SIDE_CURSORS': True,  # safe with pooled connections
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


